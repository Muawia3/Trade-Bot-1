"""
SQLAlchemy ORM model for trading signals generated by strategies or AI.
"""

from datetime import datetime, timezone
from typing import Any, Dict, Optional

from sqlalchemy import Boolean, DateTime, Float, Index, JSON, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.database.base import Base, UUIDMixin


class Signal(Base, UUIDMixin):
    """
    Represents an actionable or informative trading signal.
    Stores the trigger indicators snapshot, confidence score, and execution status.
    """

    __tablename__ = "signals"

    symbol: Mapped[str] = mapped_column(String(20), nullable=False, index=True)
    signal_type: Mapped[str] = mapped_column(String(10), nullable=False)  # 'BUY', 'SELL', 'HOLD'
    strategy_name: Mapped[str] = mapped_column(String(50), nullable=False, index=True)
    timeframe: Mapped[str] = mapped_column(String(10), nullable=False, default="M15")
    confidence: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)  # 0.0 to 1.0
    entry_price: Mapped[float] = mapped_column(Float, nullable=False)
    stop_loss: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    take_profit: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    indicators_snapshot: Mapped[Optional[Dict[str, Any]]] = mapped_column(
        JSON, nullable=True
    )
    reasoning: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        index=True,
    )
    expired_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    acted_on: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)

    __table_args__ = (
        Index("idx_signals_symbol_created", "symbol", "created_at"),
        Index("idx_signals_acted_created", "acted_on", "created_at"),
    )

    def __repr__(self) -> str:
        return (
            f"<Signal id={self.id} symbol={self.symbol} type={self.signal_type} "
            f"confidence={self.confidence} acted_on={self.acted_on}>"
        )
